-- Harvest Rentals: optional profile photos.
-- Run this ONCE in the Supabase SQL editor. Safe to run again.

-- 1. Where the photo is stored for each profile ----------------------------------
alter table public.profiles
  add column if not exists avatar_path text
  check (avatar_path is null or char_length(avatar_path) <= 300);

-- Users may change their own photo (the existing "update own profile" policy
-- already limits each user to their own row).
grant update (avatar_path) on table public.profiles to authenticated;

-- 2. Photo storage ---------------------------------------------------------------
-- Photos are stored as <auth.uid()>/<file>.jpg. The bucket is public so the map
-- and booking cards can show them; writes are limited to the user's own folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'avatars',
  'avatars',
  true,
  2097152,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "avatars_public_read" on storage.objects;
create policy "avatars_public_read"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'avatars');

drop policy if exists "avatars_insert_own" on storage.objects;
create policy "avatars_insert_own"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "avatars_update_own" on storage.objects;
create policy "avatars_update_own"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = auth.uid()::text
  )
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "avatars_delete_own" on storage.objects;
create policy "avatars_delete_own"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

notify pgrst, 'reload schema';
